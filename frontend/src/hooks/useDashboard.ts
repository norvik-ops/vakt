import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query'
import { apiFetch } from '../api/client'

export interface BackupStatus {
  last_backup_at: string | null
  stale: boolean
}

export function useBackupStatus() {
  return useQuery<BackupStatus>({
    queryKey: ['dashboard', 'backup-status'],
    queryFn: () => apiFetch<BackupStatus>('/dashboard/backup-status'),
    staleTime: 5 * 60_000,
  })
}

/**
 * Dashboard score: the org-wide implementation level (readiness, ADR-0086) —
 * the same number as `overall_readiness` in the aggregate, the framework
 * detail and the executive summary PDF. It replaced the old "Security Score"
 * (base 70 + 10 per framework), which showed 70/100 on an empty instance.
 */
export interface DashboardScore {
  /** Readiness rounded to a whole percent, 0–100. */
  score: number
  /** False while no applicable control exists — show "no data yet", not 0 %. */
  has_data: boolean
  /** The pooled tally behind `score`. */
  readiness: OverallReadiness
  /** Kept for older clients; finding/breach counters are always 0 (archived modules). */
  components: {
    critical_findings: number
    high_findings: number
    open_breaches: number
    active_frameworks: number
  }
}

/**
 * Fetches the current dashboard score (implementation level).
 * Data is considered fresh for 60 seconds; background refetches keep the header
 * score indicator up-to-date without hammering the API on every render.
 */
export function useDashboardScore() {
  return useQuery<DashboardScore>({
    queryKey: ['dashboard', 'score'],
    queryFn: () => apiFetch<DashboardScore>('/dashboard/score'),
    staleTime: 10_000,
  })
}

/**
 * A single in-app notification generated by any Vakt module.
 */
export interface UserNotification {
  id: string
  title: string
  /** Full notification body — may contain markdown. */
  body: string
  /** Severity level; drives the icon and colour shown in the notification list. */
  type: 'info' | 'warning' | 'error'
  /** Source module identifier (e.g. `"vaktscan"`, `"vaktcomply"`). */
  module: string
  /** Whether the current user has already seen the notification. */
  read: boolean
  /** RFC 3339 UTC timestamp of when the notification was created. */
  created_at: string
}

/**
 * Fetches the current user's notification list.
 *
 * Sprint 17 S17-4: Polling-Interval entfernt — der NotificationBell verbindet
 * sich jetzt zusätzlich mit useNotificationStream und ruft bei jeder neuen
 * Notification queryClient.invalidateQueries(['dashboard', 'notifications'])
 * auf. staleTime bleibt 30 s als Cache-Hint für TabSwitch-Refetches.
 */
export function useNotifications() {
  return useQuery<UserNotification[]>({
    queryKey: ['dashboard', 'notifications'],
    queryFn: () => apiFetch<UserNotification[]>('/dashboard/notifications'),
    staleTime: 30_000,
  })
}

/**
 * Marks a single notification as read by its ID and invalidates the list cache.
 * The mutation variable is the notification `id` string.
 */
export function useMarkNotificationRead() {
  const queryClient = useQueryClient()
  return useMutation<undefined, Error, string>({
    mutationFn: (id) => apiFetch<undefined>(`/dashboard/notifications/${id}/read`, { method: 'POST' }),
    onSuccess: () => { void queryClient.invalidateQueries({ queryKey: ['dashboard', 'notifications'] }) },
  })
}

/**
 * Marks every unread notification as read in a single API call,
 * then invalidates the notification list so the bell badge clears immediately.
 */
export function useMarkAllRead() {
  const queryClient = useQueryClient()
  return useMutation<undefined>({
    mutationFn: () => apiFetch<undefined>('/dashboard/notifications/read-all', { method: 'POST' }),
    onSuccess: () => { void queryClient.invalidateQueries({ queryKey: ['dashboard', 'notifications'] }) },
  })
}

// ---------------------------------------------------------------------------
// Aggregate dashboard — executive compliance summary
// ---------------------------------------------------------------------------

export interface FrameworkScore {
  framework_id: string
  framework_name: string
  total_controls: number // applicable controls (not_applicable excluded)
  implemented_controls: number // effective status implemented or covered
  score_pct: number // canonical readiness (ADR-0086), same number as framework overview and detail
}

export interface RiskSummary {
  id: string
  title: string
  likelihood: number
  impact: number
  score: number
  status: string
}

export interface ActivityEntry {
  id: string
  action: string
  entity_type: string
  user_email: string
  created_at: string
}

/** Org-wide readiness, pooled over all frameworks in the backend (ADR-0086). */
export interface OverallReadiness {
  covered: number
  partial: number
  applicable: number
  score_pct: number
}

export interface DashboardAggregate {
  framework_scores: FrameworkScore[]
  overall_readiness: OverallReadiness
  open_capas: number
  overdue_controls: number
  overdue_tasks: number
  critical_risks: number
  top_risks: RiskSummary[]
  recent_activity: ActivityEntry[]
  policies_total: number
  policies_approved: number
}

/**
 * Fetches the aggregated executive compliance summary.
 * Refreshes every 60 seconds and on window focus.
 */
export function useDashboardAggregate() {
  return useQuery<DashboardAggregate>({
    queryKey: ['dashboard', 'aggregate'],
    queryFn: () => apiFetch<DashboardAggregate>('/dashboard/aggregate'),
    staleTime: 30_000,
    refetchInterval: 60_000,
  })
}
